"""Build js/data/baseEvents.js: the base pack's events, from tools/events/*.py and the roll tables.

Usage (from the repository root, after build-tables.py):
    python tools/build-events.py

Each tools/events/<table>.py writes its events with the shorthand in helpers.py. An event written
as ev('asteroids', steps) takes its id, title, rule text and weight from that row of the roll table
(js/data/tables.js); events that replace a row, or split it by a plain dice roll, give their own.
The build checks that every row of the five tables is covered and that a split row's weights add
back up to the printed weight.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "events"))

import travel, character, campaign, exploration, trade  # noqa: E402

TABLES_JS = ROOT / "js" / "data" / "tables.js"
OUTPUT = ROOT / "js" / "data" / "baseEvents.js"
MODULES = [travel, character, campaign, exploration, trade]


def load_tables():
    text = TABLES_JS.read_text(encoding="utf8")
    start = text.index("window.LP.data.tables = ") + len("window.LP.data.tables = ")
    return json.loads(text[start:text.rindex("};") + 1])


def number(value):
    value = round(value, 2)
    return int(value) if value == int(value) else value


def build_module(module, tables, errors):
    table = tables[module.TABLE]
    rows = {r["id"]: r for r in table["rows"]}
    label = table["labelColumn"]
    body = next(c for c in table["columns"] if not c.startswith("weight") and c != label)
    events = []
    used = {}
    for e in module.EVENTS:
        row = rows.get(e["source"])
        if not row:
            errors.append("%s: no row '%s'" % (module.TABLE, e["source"]))
            continue
        weight = e["weight"] if e["weight"] is not None else row["weight"]
        out = {
            "id": e["id"],
            "table": module.KEY,
            "weight": number(weight),
            "title": e["title"] or row[label],
            "text": e["text"] if e["text"] is not None else row[body],
        }
        if e["group"]:
            out["group"] = e["group"]
        if e["requires"]:
            out["requires"] = e["requires"]
        out["steps"] = e["steps"]
        if e["fallback"]:
            out["fallback"] = e["fallback"]
        events.append(out)
        used.setdefault(e["source"], []).append(weight)
    for row_id, row in rows.items():
        if row_id not in used:
            errors.append("%s: row '%s' has no event" % (module.TABLE, row_id))
    for row_id, weights in used.items():
        if len(weights) > 1 and rows.get(row_id) and abs(sum(weights) - rows[row_id]["weight"]) > 0.02:
            errors.append("%s: the split of '%s' weighs %.2f, not %s" % (module.TABLE, row_id, sum(weights), rows[row_id]["weight"]))
    return events


def main():
    tables = load_tables()
    errors = []
    events = []
    fragments = []
    for module in MODULES:
        events.extend(build_module(module, tables, errors))
        fragments.extend(module.FRAGMENTS)
    ids = [e["id"] for e in events]
    for dup in sorted({i for i in ids if ids.count(i) > 1}):
        errors.append("event id '%s' is used more than once" % dup)
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    body = json.dumps({"events": events, "fragments": fragments}, indent=1, ensure_ascii=False)
    OUTPUT.write_text(
        "// GENERATED by tools/build-events.py from tools/events/*.py and the roll tables. Do not edit by hand.\n"
        "window.LP.data = window.LP.data || {};\n"
        "window.LP.data.baseEvents = " + body + ";\n",
        encoding="utf8",
    )
    print("%d events, %d fragments -> %s" % (len(events), len(fragments), OUTPUT.relative_to(ROOT)))


if __name__ == "__main__":
    main()
