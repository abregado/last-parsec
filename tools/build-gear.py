"""Build js/data/gear.js (GENERATED) from the local rulebook PDF.

Weapon stats (range, shots, damage, traits), the weapon trait rules, and what each
piece of gear does. The PDF is copyrighted and stays local: only the generated data
is committed, like the roll tables.

Usage: python tools/build-gear.py [path/to/rulebook.pdf]
Needs: pip install pdfplumber
"""
import json
import re
import sys
from pathlib import Path

import pdfplumber

ROOT = Path(__file__).resolve().parent.parent
PDF = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / '5PH-Rulebook-210408T.pdf'
OUT = ROOT / 'js' / 'data' / 'gear.js'

# PDF page numbers (1-based) of "Weapons and Gear".
WEAPON_PAGE = 52
MOD_SIGHT_PAGE = 55
EQUIPMENT_PAGES = [56, 57, 58, 59, 60]

# The trait rules (p.51), whose two-column layout does not extract cleanly.
TRAITS = {
    'Area': 'Resolve all shots against the initial target (they cannot be spread), then one bonus shot against every figure within 2".',
    'Clumsy': '-1 to Brawling rolls, if the opponent has higher Speed.',
    'Critical': 'A natural 6 on the To Hit roll inflicts 2 Hits on the target.',
    'Elegant': 'When Brawling, the fighter may reroll the die. Enemies always reroll if they have a lower total than their opponent, and can improve the result.',
    'Focused': 'All shots must be against a single target.',
    'Heavy': '-1 penalty to Hit if the firer moved this round.',
    'Impact': 'If the target is Stunned, place a second Stun marker.',
    'Melee': '+2 to Brawling rolls.',
    'Piercing': 'Ignore Armor Saving Throws.',
    'Pistol': '+1 to Brawling rolls.',
    'Single use': 'The item can be used only once and must be deducted from the available supply. The Panic Fire rule (p.46) cannot be used with Single use weapons.',
    'Snap Shot': '+1 to Hit within 6".',
    'Stun': 'All targets are automatically Stunned. No damage rolls take place.',
    'Terrifying': 'Any target hit must retreat 1D6" away from the firer.',
}


def clean(text):
    """One line of text; the PDF's inch marks (after a digit) become a plain double quote."""
    text = (text or '').replace('\n', ' ')
    text = re.sub(r'(?<=\d)[”″�]', '"', text)
    return re.sub(r'\s+', ' ', text).strip()


def fix_quotes(text):
    """Any other odd quote mark between letters is an apostrophe."""
    text = clean(text)
    return re.sub(r'(?<=[A-Za-z])[�‘”]', '’', text)


def key(name):
    """Lookup key: lowercase letters and digits only ("Marksman's rifle" = "Marksmans rifle")."""
    return re.sub(r'[^a-z0-9]+', '', name.lower().replace('’', '').replace("'", ''))


def title(name):
    return fix_quotes(name)


def tables(pdf, page):
    return pdf.pages[page - 1].extract_tables()


def main():
    weapons, items = {}, {}
    with pdfplumber.open(PDF) as pdf:
        for row in tables(pdf, WEAPON_PAGE)[0][1:]:
            name = title(row[0])
            rng = fix_quotes(row[1])
            shots = row[2].strip()
            damage = row[3].strip()
            traits = [] if row[4].strip() in ('-', '') else [t.strip() for t in clean(row[4]).split(',') if t.strip()]
            weapons[key(name)] = {
                'name': name,
                'range': rng.replace('"', '') + ('"' if rng != 'Brawl' else ''),
                'shots': None if shots in ('-', '') else int(shots),
                'damage': damage,
                'traits': traits,
            }

        mods, sights = tables(pdf, MOD_SIGHT_PAGE)
        for row in mods[1:]:
            items[key(row[0])] = {'name': title(row[0]), 'kind': 'Gun mod', 'text': fix_quotes(row[1])}
        for row in sights[1:]:
            items[key(row[0])] = {'name': title(row[0]), 'kind': 'Gun sight', 'text': fix_quotes(row[1])}

        for page in EQUIPMENT_PAGES:
            for table in tables(pdf, page):
                head = [clean(c).upper() for c in table[0]]
                kind = {'CONSUMABLE': 'Consumable', 'PROTECTION': 'Protection', 'IMPLANT': 'Implant',
                        'UTILITY DEVICE': 'Utility device', 'ITEM': 'Gear'}.get(head[0])
                if not kind:
                    continue
                for row in table[1:]:
                    if not row[0] or not row[0].strip():
                        continue
                    name = title(row[0])
                    text = fix_quotes(row[-1])
                    if kind == 'Protection':
                        text = fix_quotes(row[1]) + ': ' + text
                    items[key(name)] = {'name': name, 'kind': kind, 'text': text}

    weapons['duelingpistol'] = weapons['duellingpistol']  # the tables spell it one way, the book the other
    data = {'weapons': weapons, 'traits': TRAITS, 'items': items}
    OUT.write_text(
        '/* GENERATED by tools/build-gear.py from the rulebook. Do not edit by hand. */\n'
        '(function (LP) {\n  \'use strict\';\n  LP.data = LP.data || {};\n  LP.data.gear = '
        + json.dumps(data, indent=2, ensure_ascii=False) + ';\n})(window.LP);\n',
        encoding='utf-8')
    print('weapons', len(weapons), 'items', len(items))


if __name__ == '__main__':
    main()
